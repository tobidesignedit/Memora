package com.memora.app.data

import kotlinx.serialization.Serializable

@Serializable
data class ExtractedEntities(
  val people: List<String> = emptyList(),
  val organizations: List<String> = emptyList(),
  val dates: List<String> = emptyList(),
  val amounts: List<String> = emptyList(),
  val locations: List<String> = emptyList(),
  val contacts: List<String> = emptyList(),
)

@Serializable
data class MemoryItem(
  val id: String = "",
  val uid: String = "local",
  val kind: String = "note",
  val title: String = "",
  val summary: String = "",
  val rawText: String = "",
  val extractedText: String = "",
  val url: String? = null,
  val sourceApp: String? = null,
  val mediaMimeType: String? = null,
  val mediaFileName: String? = null,
  val mediaLocalKey: String? = null,
  val mediaThumbnail: String? = null,
  val tags: List<String> = emptyList(),
  val category: String = "Personal Vault",
  val entities: ExtractedEntities = ExtractedEntities(),
  val actionItems: List<String> = emptyList(),
  val personalNote: String? = null,
  val threadId: String? = null,
  val threadTopic: String? = null,
  val importance: String = "normal",
  val language: String? = "en",
  val inferenceSource: String = "offline_heuristic",
  val inferenceModel: String? = null,
  val inferenceLatencyMs: Long = 0L,
  val privacyMode: String = "prefer_on_device",
  val syncStatus: String = "pending",
  val pinned: Boolean = false,
  val favorite: Boolean = false,
  val archived: Boolean = false,
  val createdAt: Long = System.currentTimeMillis(),
  val updatedAt: Long = System.currentTimeMillis(),
)

@Serializable
data class ReminderItem(
  val id: String = "",
  val uid: String = "local",
  val memoryId: String? = null,
  val memoryTitle: String? = null,
  val memoryThumbnail: String? = null,
  val title: String = "",
  val dueDateIso: String = "",
  val dueTime: String? = null,
  val venue: String? = null,
  val organizer: String? = null,
  val category: String = "event",
  val priority: String = "medium",
  val status: String = "suggested",
  val recurrence: String = "none",
  val conflictWithId: String? = null,
  val notes: String? = null,
  val createdAt: Long = System.currentTimeMillis(),
  val updatedAt: Long = System.currentTimeMillis(),
)

@Serializable
data class MemoryThread(
  val id: String = "",
  val uid: String = "local",
  val title: String = "",
  val topic: String = "",
  val summary: String = "",
  val memoryIds: List<String> = emptyList(),
  val keyInsights: List<String> = emptyList(),
  val nextActions: List<String> = emptyList(),
  val autoGenerated: Boolean = true,
  val inferenceSource: String? = null,
  val updatedAt: Long = System.currentTimeMillis(),
)

@Serializable
data class BenchmarkEntry(
  val id: String,
  val operation: String,
  val source: String,
  val modelUsed: String,
  val latencyMs: Long,
  val timestamp: Long,
)

@Serializable
data class VaultSnapshot(
  val memories: List<MemoryItem> = emptyList(),
  val reminders: List<ReminderItem> = emptyList(),
  val threads: List<MemoryThread> = emptyList(),
  val benchmarks: List<BenchmarkEntry> = emptyList(),
  val indexedMediaKeys: Set<String> = emptySet(),
  val autoIndexEnabled: Boolean = false,
  val autoIndexScope: String = "everything", // "everything" | "all_photos" | "screenshots"
  val autoIndexLocalOnly: Boolean = false,
)

data class SearchCitation(
  val memoryId: String,
  val title: String,
  val excerpt: String,
)

data class SearchAnswer(
  val query: String,
  val answer: String,
  val citations: List<SearchCitation>,
  val suggestedFollowUps: List<String>,
  val source: String,
  val modelUsed: String,
  val latencyMs: Long,
)

data class RemoteConfigSnapshot(
  val cloudModelFast: String = "gemini-3.5-flash-lite",
  val cloudModelPro: String = "gemini-3.8-flash",
  val ttsModel: String = "gemini-3.1-flash-tts-preview",
  val defaultInferenceMode: String = "prefer_on_device",
  val maxContextMemories: Int = 24,
  val latestAppVersionCode: Int = 2,
  val latestAppVersionName: String = "1.1.0",
  val apkDownloadUrl: String = "",
  val apkReleaseNotes: String = "",
)
